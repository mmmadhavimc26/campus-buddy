import test from 'node:test';
import assert from 'node:assert/strict';
import {locations,paths} from '../src/data.js';
import {findRoute,routeCoordinates} from '../src/graph.js';
test('app initializes and search, selection and routing use the same interactive map',async()=>{
  const elements=new Map(),events=new Map();
  const element=id=>{if(id==='algorithm')throw new Error('Algorithm selector must not be accessed');if(!elements.has(id))elements.set(id,{value:'',innerHTML:'',textContent:'',hidden:false,dataset:{},setAttribute(){},addEventListener(){},focus(){},getBoundingClientRect(){return {width:1000,height:760};}});return elements.get(id);};
  globalThis.document={getElementById:element,addEventListener:(name,fn)=>events.set(name,fn)};
  globalThis.window={CAMPUS_CONFIG:{}};
  globalThis.localStorage={getItem(){return null;},setItem(){}};
  await import('../src/app.js');
  assert.ok(!element('directory').innerHTML.includes('Path junction'));
  assert.ok(!element('start').innerHTML.includes('j-west'));
  assert.ok(!element('campus-map').innerHTML.includes('<image'));
  element('search').value='mechanical';element('search').oninput();
  assert.match(element('directory').innerHTML,/Mechanical/);assert.ok(!element('directory').innerHTML.includes('Security Office'));
  events.get('click')({target:{closest:selector=>selector==='[data-location]'?{dataset:{location:'main'}}:null}});
  assert.match(element('building-card').innerHTML,/Also in building 11/);
  assert.match(element('building-card').innerHTML,/Administration/);
  element('start').value='firstyear';element('destination').value='electrical';
  element('route-form').onsubmit({preventDefault(){}});
  const expected=findRoute(locations,paths,'firstyear','electrical','bfs');
  const expectedPoints=routeCoordinates(locations,paths,expected.route).map(p=>p.join(',')).join(' ');
  assert.ok(element('campus-map').innerHTML.includes('class="selected-route" points="'+expectedPoints+'"'));
  assert.ok(!element('route-result').innerHTML.includes('Algorithm details'));
  assert.match(element('campus-map').innerHTML,/selected-route/);
  assert.match(element('route-result').innerHTML,/Walking time unavailable/);
  assert.ok(!element('route-result').innerHTML.includes('Path junction'));
});
